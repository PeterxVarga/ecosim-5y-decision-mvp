def main():
    p=argparse.ArgumentParser()
    p.add_argument("--r205",type=Path,required=True)
    p.add_argument("--r206",type=Path,required=True)
    p.add_argument("--r205-private-sources",type=Path,required=True)
    p.add_argument("--out-dir",type=Path,required=True)
    a=p.parse_args()
    hold(not a.out_dir.exists() and not a.out_dir.resolve().is_relative_to(ROOT),"OUTPUT_PRIVATE_AND_NEW")
    imported=exercise(include_joined=True)
    r205=json.loads(a.r205.read_text());r206=json.loads(a.r206.read_text())
