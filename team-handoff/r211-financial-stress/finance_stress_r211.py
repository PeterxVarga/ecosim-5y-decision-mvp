ROOT=Path(__file__).resolve().parents[2]
R209=ROOT/"team-handoff/r207-first-round"
sys.path.insert(0,str(R209))
from test_r209_policy_finance_reuse import exercise

SCHEMA="ECOSIM_R211_SOURCE_LINKED_INCREMENTAL_FINANCE_STRESS_V1"
STRESSES={
  "REFERENCE_NO_EXTRA_OBLIGATION":0,
  "HYPOTHETICAL_10000_EXTRA_PER_YEAR":10000,
  "HYPOTHETICAL_25000_EXTRA_PER_YEAR":25000,
}
def hold(ok,why):
    if not ok:raise ValueError("HOLD_"+why)
def num(v,why):
    hold(type(v) in (int,float) and math.isfinite(v),"FINITE_"+why)
    return float(v)
def approx(a,b,why,epsilon=0.0001):
    hold(abs(num(a,why)-num(b,why))<=epsilon,"ACCOUNTING_"+why)
def sha(p):return hashlib.sha256(Path(p).read_bytes()).hexdigest()

def model_receipts(r205,r206,r205_path,source_dir):
    hold(r205.get("schema")=="ECOSIM_R205_HISTORICAL_LIBRARY_SOURCE_RECONCILIATION_V1" and
         r205.get("status")=="PASS_PREVIOUSLY_UPLOADED_EVIDENCE_RECONCILED_LIVE_HOLD" and
         r205.get("mode")=="historical-test" and r205.get("gameplay_gate")=="STOP" and
         r205.get("game_writes")==0,"R205_HISTORICAL_GATE")
    hold(r206.get("schema")=="ECOSIM_R206_REUSED_SEARCH_HISTORICAL_CANDIDATES_V1" and
         r206.get("status")=="PASS_HISTORICAL_BOUNDED_SEARCH_LIVE_HOLD" and
         r206.get("mode")=="historical-test" and
         r206.get("gameplay_gate")=="STOP" and
         r206.get("game_writes")==0 and r206.get("verified_spendable_cash") is False and
         r206.get("verified_city_transition") is False,"R206_HISTORICAL_GATE")
    hold(r206.get("source_sha256",{}).get("r205_reconciliation")==sha(r205_path),"R206_R205_IDENTITY")
    expected={"income.csv":49,"loans.csv":7,"rules.csv":5,"observations.csv":24,"source_index.csv":15}
    hold(set(r205.get("source_files",{}))==set(expected),"FIVE_SOURCE_SET")
    for name,rows in expected.items():
        path=source_dir/name
        hold(path.is_file() and not path.is_symlink(),"PRIVATE_SOURCE_"+name)
        hold(r205["source_files"][name]["rows"]==rows and
             r205["source_files"][name]["normalized_sha256"]==sha(path),"PRIVATE_SOURCE_HASH_"+name)
    loan=r205.get("observed_finance_terms",{})
    hold(loan.get("loan_ceiling")=="UNKNOWN" and
         loan.get("settlement_timing")=="UNKNOWN","LOAN_UNCERTAINTY_GATE")
    grants=r205.get("observed_development_grants",{})
    hold(grants.get("actually_spendable")=="UNVERIFIED" and grants.get("timing")=="UNKNOWN",
         "GRANTS_UNCERTAINTY_GATE")
    rates=[num(r205.get("observed_long_term_loan_interest_pct"),"LONG_RATE"),
           num(r205.get("observed_short_term_loan_interest_pct"),"SHORT_RATE")]
    hold(all(0<rate<=100 for rate in rates),"OBSERVED_LOAN_RATES")
    return {
        "historical_only_long_loan_rate_pct":rates[0],
        "historical_only_short_loan_rate_pct":rates[1],
        "historical_only_grant_lines_observed_not_cash":{
            "state_p0_raw":num(grants.get("state_p0_raw"),"STATE_GRANT"),
            "company_p0_raw":num(grants.get("company_p0_raw"),"COMPANY_GRANT")},
        "loan_ceiling":"UNKNOWN","grant_disbursement":"UNKNOWN",
        "cash_recognized_from_loans_or_grants_ecu":0,
        "note":"Rates and grant rows are historical observations, excluded from liquidity math."
    }

def verify_join(receipt,joined,candidates):
    hold(receipt.get("status")=="PASS_HISTORICAL_SYNTHETIC_PARTIAL_POLICY_JOIN_ONLY" and
         receipt.get("source_class")=="SYNTHETIC_TEST_ONLY" and
         receipt.get("gameplay_gate")=="STOP" and receipt.get("game_writes")==0 and
         receipt.get("actual_spendable_cash") is False and
         receipt.get("actual_city_forecast") is False,"R209_GATE")
    hold(joined.get("schema")=="ECOSIM_R159_COMPONENT_RESOLVED_PARTIAL_FISCAL_TIMING_V1" and
         joined.get("gameplay_gate")=="STOP","R159_GATE")
    rows=joined.get("combinations",[])
    hold(len(candidates)==12 and len(rows)==36 and
         joined.get("evaluated_combinations")==36,"EXACT_12x3_COVERAGE")
    cand={c["candidate_id"]:c for c in candidates}
    hold(len(cand)==12 and len(set(c["candidate_id"] for c in candidates))==12,"CANDIDATE_IDS")
    policies=set();pairs=set();evaluated=[]
    for row in rows:
        pid=row.get("candidate_id");policy=row.get("path_id");pair=(pid,policy)
        hold(pid in cand and isinstance(policy,str) and policy and pair not in pairs,"PAIR_IDENTITY")
        hold(row.get("gameplay_gate")=="STOP" and row.get("affordability_authorized") is False
             and row.get("actual_spendable_cash_ecu") is None,"NO_REAL_CASH")
        policies.add(policy);pairs.add(pair)
        yr=row.get("annual_rows")
        hold(isinstance(yr,list) and len(yr)==5,"FIVE_YEAR_ROWS")
        cumulative_i=0.;cumulative_d=0.;prev_positive=0.;immediate_peak=0.;deferred_peak=0.
        costs=[]
        for i,y in enumerate(yr):
            hold(y.get("year")==i+1 and y.get("projects_started_ids")==cand[pid]["project_ids_by_year"][i],
                 "YEAR_PROJECT_IDENTITY")
            card=num(y.get("project_card_need_ecu"),"PROJECT_COST")
            approx(card,cand[pid]["conservative_project_need_ecu_by_year"][i],"CARD_COST")
            tax=num(y.get("four_tax_delta_ecu"),"TAX")
            op=num(y.get("six_fee_minus_covered_institutions_delta_ecu"),"OPERATING")
            fee=num(y.get("direct_six_fee_delta_ecu"),"FEE")
            instit=num(y.get("institutional_cost_delta_ecu"),"INSTITUTION")
            approx(fee-instit,op,"OPERATING_SPLIT")
            net=tax+op-card
            approx(net,y.get("partial_net_after_card_cost_ecu"),"ANNUAL_NET",0.00011)
            cumulative_i+=net
            approx(cumulative_i,y.get("cumulative_partial_net_zero_opening_cash_ecu"),"CUMULATIVE_IMMEDIATE",0.0006)
            newly_positive=num(y.get("new_positive_tax_and_fee_deltas_deferred_ecu"),"DEFERRED")
            negative=num(y.get("negative_tax_and_fee_deltas_immediate_ecu"),"NEGATIVE")
            hold(newly_positive>=0 and negative<=0,"SIGNED_REVENUE")
            dnet=prev_positive+negative-instit-card
            approx(dnet,y.get("deferred_net_after_card_cost_ecu"),"ANNUAL_DEFERRED_NET",0.0007)
            cumulative_d+=dnet
            approx(cumulative_d,y.get("cumulative_deferred_net_zero_opening_cash_ecu"),"CUMULATIVE_DEFERRED",0.001)
            prev_positive=newly_positive
            costs.append(card)
            immediate_peak=max(immediate_peak,-cumulative_i)
            deferred_peak=max(deferred_peak,-cumulative_d)
        approx(sum(costs),cand[pid]["five_year_conservative_project_need_ecu"],"FIVE_YEAR_CARDS",0.0007)
        approx(immediate_peak,row.get("hypothetical_peak_zero_opening_cash_shortfall_immediate_ecu"),
               "R159_IMMEDIATE_PEAK",0.001)
        approx(deferred_peak,row.get("hypothetical_peak_zero_opening_cash_shortfall_positive_receipts_deferred_ecu"),
               "R159_DEFERRED_PEAK",0.001)
        # Stress is INCREMENTAL to an unknown baseline. It does not represent
        # cash availability. Never add historical R205 grant/loan observations.
        risks=[]
        for name,additional in STRESSES.items():
            ipeak=dpeak=0.; immediate=deferred=0.
            for y in yr:
                immediate+=num(y["partial_net_after_card_cost_ecu"],"IMMEDIATE_DELTA")-additional
                deferred+=num(y["deferred_net_after_card_cost_ecu"],"DEFERRED_DELTA")-additional
                ipeak=max(ipeak,-immediate);dpeak=max(dpeak,-deferred)
            if additional==0:
                approx(ipeak,immediate_peak,"NO_SHOCK_IMMEDIATE",0.001)
                approx(dpeak,deferred_peak,"NO_SHOCK_DEFERRED",0.001)
            risks.append({"scenario":name,
                          "additional_unmodeled_obligation_assumption_per_year_ecu":additional,
                          "sampled_incremental_buffer_against_unknown_reference_path_immediate_ecu":round(ipeak,2),
                          "sampled_incremental_buffer_against_unknown_reference_path_deferred_ecu":round(dpeak,2),
                          "actual_available_cash":None,
                          "real_financing_approval":False})
        evaluated.append({"candidate_id":pid,"policy_path":policy,
                          "first_year_project_ids":yr[0]["projects_started_ids"],
                          "five_year_card_cost_ecu":round(sum(costs),2),
                          "five_year_partial_net_delta_ecu":round(cumulative_i,2),
                          "mapped_terminal_proxy_delta_conditional":num(row.get("conditional_terminal_mapped_proxy_delta"),"PROXY"),
                          "stress_cases":risks})
    hold(len(policies)==3 and set(pairs)=={(c,p) for c in cand for p in policies},"COMPLETE_CARTESIAN_JOIN")
    return evaluated

def rank_options(rows):
    groups=defaultdict(list)
    for row in rows:groups[row["candidate_id"]].append(row)
    summaries=[]
    for cid,ls in sorted(groups.items()):
        hold(len(ls)==3 and len({x["policy_path"] for x in ls})==3,"THREE_POLICIES_PER_PLAN")
        maxrisk=max(x["stress_cases"][-1]["sampled_incremental_buffer_against_unknown_reference_path_deferred_ecu"] for x in ls)
        baseline_risk=max(x["stress_cases"][0]["sampled_incremental_buffer_against_unknown_reference_path_deferred_ecu"] for x in ls)
        worstscore=min(x["mapped_terminal_proxy_delta_conditional"] for x in ls)
        costs={x["five_year_card_cost_ecu"] for x in ls}
        hold(len(costs)==1,"CANDIDATE_COST_DIFFERS_ACROSS_POLICIES")
        summaries.append({"candidate_id":cid,"budget_tier":cid.split("_")[0],
                "first_year_project_ids":ls[0]["first_year_project_ids"],
                "five_year_card_cost_ecu":costs.pop(),
                "worst_sampled_policy_proxy_delta":round(worstscore,7),
                "worst_relative_buffer_zero_extra_ecu":baseline_risk,
                "worst_relative_buffer_25k_extra_per_year_ecu":maxrisk,
                "not_a_real_funding_gap":True})
    chosen=[]
    for tier in ("LOW","MID","HIGH"):
        pool=[v for v in summaries if v["budget_tier"]==tier]
        hold(len(pool)==4,"FOUR_CANDIDATES_PER_TIER")
        # Not a single optimum: choose the least demanding relative liquidity
        # stress in each tier; retain cost and proxy tradeoff for the operator.
        chosen.append(min(pool,key=lambda v:(v["worst_relative_buffer_25k_extra_per_year_ecu"],
                                            -v["worst_sampled_policy_proxy_delta"],
                                            v["five_year_card_cost_ecu"],v["candidate_id"])))
    return summaries,chosen

def build(receipt,joined,candidates,r205,r206,r205_path,source_dir):
    source_info=model_receipts(r205,r206,r205_path,source_dir)
    rows=verify_join(receipt,joined,candidates)
    summaries,choices=rank_options(rows)
    return {"schema":SCHEMA,
            "status":"PASS_SOURCE_LINKED_HISTORICAL_DELTA_STRESS_NOT_LIVE_FUNDING",
            "mode":"historical-test","underlying_policy_class":"SYNTHETIC_TEST_ONLY",
            "original_calculator":"R153_R154_R155_R158_R159_REUSED_R209",
            "cross_model_r205_r206_provenance":source_info,
            "source_hashes":{"r205":sha(r205_path)},
            "combination_count":len(rows),"scenario_count":len(STRESSES),
            "incremental_stress_case_count":sum(len(x["stress_cases"]) for x in rows),
            "five_year_project_schedules":len(summaries),
            "stress_assumptions_ecu_per_year":STRESSES,
            "cases":rows,"plans":summaries,"three_budget_tier_diagnostics":choices,
            "actual_city_cash_balance":None,"verified_spendable_budget":None,
            "loan_authorization":False,"grant_disbursement_verified":False,
            "complete_city_model":False,"score_forecast_validated":False,
            "gameplay_gate":"STOP","game_writes":0,
            "non_inference":["R159 computes only deltas versus unknown fixed baseline; not total cash",
                             "Hypothetical incremental buffer is NOT actual opening cash or funding gap",
                             "10k/25k annual extra obligations are synthetic assumptions",
                             "Loan rates/grant lines are historical observations, not financing authority",
                             "Historical p1 PLAN is not a later realized FACT"]}

